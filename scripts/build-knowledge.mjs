// Bundles everything the chat assistant may know into worker/src/knowledge.generated.ts:
// the profile, every case study, and knowledge/faq.md. The site's own content is the single
// source of truth, so the chat never drifts from what the pages say.
// Runs automatically before `npm run dev` / `npm run deploy` in worker/.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");

const profile = JSON.parse(read("src/data/profile.json"));

const sections = [];

sections.push(`# Profile
Name: ${profile.name}
Role: ${profile.role}
Location: ${profile.location}
Availability: ${profile.availability}
Pitch: ${profile.pitch}
Email: ${profile.email}
GitHub: ${profile.links.github}
LinkedIn: ${profile.links.linkedin}
Book a call: ${profile.links.booking}
Resume: ${profile.resume}

## About
${profile.about.join("\n\n")}

## Education
${profile.education.map((e) => `- ${e.school} (${e.period}): ${e.detail}`).join("\n")}

## Skills (with the project that proves each)
${profile.skills.map((s) => `- ${s.name}: ${s.note} (see /projects/${s.proof}/)`).join("\n")}`);

const dir = "src/content/projects";
for (const file of readdirSync(join(root, dir)).filter((f) => f.endsWith(".md")).sort()) {
  const slug = file.replace(/\.md$/, "");
  sections.push(`# Project: ${slug}\nCase study page: /projects/${slug}/\n\n${read(`${dir}/${file}`).trim()}`);
}

sections.push(read("knowledge/faq.md").trim());

const knowledge = sections.join("\n\n---\n\n");
writeFileSync(
  join(root, "worker/src/knowledge.generated.ts"),
  `// Generated by scripts/build-knowledge.mjs — do not edit by hand.\nexport const KNOWLEDGE = ${JSON.stringify(knowledge)};\n`,
);
console.log(`knowledge: ${sections.length} sections, ${knowledge.length} chars`);
